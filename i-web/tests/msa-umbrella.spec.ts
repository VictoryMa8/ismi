import { readFileSync } from 'node:fs'
import { expect, test } from '@playwright/test'
import { chooseCourse, expectViewedCourse } from './courseSwitcher'

for (const width of [390, 1280]) test(`MSA groups its paths through discovery, settings and offline return at ${width}px`, async ({ page, context }, info) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/')
  const cards = page.locator('.tracks-grid article')
  await expect(cards).toHaveCount(4)
  await expect(page.locator('.tracks-grid [data-course="quranic"]')).toHaveCount(0)
  const msa = page.locator('.tracks-grid [data-course="msa"]')
  await expect(msa).toContainText('Quranic Arabic path')
  await expect(msa).toContainText('Planned')
  await msa.getByRole('link', { name: 'View course status' }).click()
  await expectViewedCourse(page, 'msa')
  const paths = page.getByRole('region', { name: 'Modern Standard Arabic paths' })
  await paths.getByRole('button', { name: 'Quranic Arabic', exact: true }).click()
  await expectViewedCourse(page, 'quranic')
  await expect(page.locator('.banner-detail')).toContainText('MSA · Quranic Arabic')
  await expect(page.locator('.track-grid .track-card')).toHaveCount(3) // MSA, French, Khmer are planned here.
  await expect(page.locator('.track-grid .track-card').filter({ has: page.getByRole('heading', { name: 'Modern Standard Arabic', exact: true }) })).toContainText('General MSA and Quranic Arabic paths')
  await page.getByRole('link', { name: 'Account', exact: true }).click()
  const group = page.getByRole('group', { name: 'Modern Standard Arabic', exact: true })
  await group.getByRole('checkbox', { name: /Quranic Arabic/ }).check()
  await group.getByRole('checkbox', { name: /General MSA/ }).check()
  await page.getByLabel('Primary course', { exact: true }).selectOption('quranic')
  await page.getByRole('button', { name: 'Save study settings' }).click()
  await expect(page.getByRole('button', { name: 'Save study settings' })).toBeEnabled()
  await chooseCourse(page, 'msa')
  await expect(page.getByLabel('Primary course', { exact: true })).toHaveValue('quranic')
  await expect(group.getByRole('checkbox', { name: /Quranic Arabic/ })).toBeChecked()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await context.setOffline(true)
  await page.reload()
  await expectViewedCourse(page, 'msa')
  await expect(page.getByLabel('Primary course', { exact: true })).toHaveValue('quranic')
  await expect(group.getByRole('checkbox', { name: /General MSA/ })).toBeChecked()
  await chooseCourse(page, 'quranic')
  await expect(page.getByLabel('Primary course', { exact: true })).toHaveValue('quranic')
  await page.getByRole('link', { name: 'Courses', exact: true }).click()
  await expect(paths.getByRole('button', { name: 'Quranic Arabic', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(await page.locator('body').evaluate(el => el.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: info.outputPath(`msa-paths-${width}.png`), fullPage: true })
  await context.setOffline(false)
})

test('existing Quranic account preferences and API path identities survive the umbrella', async ({ request, page }) => {
  const catalog = await (await request.get('/api/courses')).json()
  expect(catalog.filter((c: { course: { groupId: string } }) => c.course.groupId === 'msa').map((c: { course: { id: string } }) => c.course.id)).toEqual(['msa', 'quranic'])
  const csrf = await (await page.request.get('/api/auth/csrf')).json()
  const headers = { 'X-CSRF-TOKEN': csrf.token }
  expect((await page.request.post('/api/auth/register', { headers, data: { displayName: 'MSA learner', email: 'msa-umbrella@example.test', password: 'long test password' } })).ok()).toBeTruthy()
  const preferences = { goalMinutes: 15, selectedTrackIds: ['msa', 'quranic'], primaryTrack: 'quranic' }
  const settings = await (await page.request.get('/api/study-settings')).json()
  const freshCsrf = await (await page.request.get('/api/auth/csrf')).json()
  expect((await page.request.post('/api/study-settings', { headers: { 'X-CSRF-TOKEN': freshCsrf.token }, data: { revision: settings.revision, preferences } })).ok()).toBeTruthy()
  await page.goto('/#/account')
  await expect(page.getByLabel('Primary course', { exact: true })).toHaveValue('quranic')
  await chooseCourse(page, 'msa')
  await chooseCourse(page, 'quranic')
  expect((await (await page.request.get('/api/study-settings')).json()).preferences).toEqual(preferences)
  await expect(page.locator('.app-shell')).toContainText(`Beta ${JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version}`)
})
