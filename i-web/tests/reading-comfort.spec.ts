import { readFileSync } from 'node:fs'
import { expect, test, type Page } from '@playwright/test'
const pack = JSON.parse(readFileSync(new URL('../../content/levantine/everyday-01/revisions/guided-teaching/01-lesson.json', import.meta.url), 'utf8'))
async function settings(page: Page) {
  await page.goto('/#/account')
  await page.getByRole('button', { name: 'Reading comfort', exact: true }).click()
  return page.getByRole('dialog', { name: 'Reading comfort', exact: true })
}
test('offline preferences, separate courses, reset and cross-tab changes', async ({ page, context }) => {
  const panel = await settings(page)
  await panel.getByRole('combobox', { name: 'Target text size', exact: true }).selectOption('200')
  await panel.getByRole('combobox', { name: 'Line spacing', exact: true }).selectOption('spacious')
  await panel.getByRole('combobox', { name: 'Transliteration', exact: true }).selectOption('tap')
  await expect(panel.getByRole('status')).toHaveText('Saved on this device.')
  await panel.getByRole('combobox', { name: 'Course', exact: true }).selectOption('quranic')
  await expect(panel.getByRole('combobox', { name: 'Target text size', exact: true })).toHaveValue('100')
  await panel.getByRole('combobox', { name: 'Target text size', exact: true }).selectOption('125')
  await panel.getByRole('combobox', { name: 'Course', exact: true }).selectOption('msa')
  await expect(panel.getByRole('combobox', { name: 'Target text size', exact: true })).toHaveValue('100')
  await panel.getByRole('combobox', { name: 'Course', exact: true }).selectOption('levantine')
  await expect(panel.getByRole('combobox', { name: 'Target text size', exact: true })).toHaveValue('200')
  const other = await context.newPage(), second = await settings(other)
  await expect(second.getByRole('combobox', { name: 'Target text size', exact: true })).toHaveValue('200')
  await second.getByRole('combobox', { name: 'Target text size', exact: true }).selectOption('150')
  await expect(panel.getByRole('combobox', { name: 'Target text size', exact: true })).toHaveValue('150')
  await second.getByRole('button', { name: 'Reset this course' }).click()
  await expect(panel.getByRole('combobox', { name: 'Target text size', exact: true })).toHaveValue('100')
  await panel.getByRole('combobox', { name: 'Course', exact: true }).selectOption('quranic')
  await expect(panel.getByRole('combobox', { name: 'Target text size', exact: true })).toHaveValue('125')
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await context.setOffline(true)
  await page.reload()
  await page.getByRole('button', { name: 'Reading comfort', exact: true }).click()
  await panel.getByRole('combobox', { name: 'Course', exact: true }).selectOption('quranic')
  await expect(panel.getByRole('combobox', { name: 'Target text size', exact: true })).toHaveValue('125')
})
